// Loopback fictional UI only. The dedicated preview injects mock actions, with
// no production imports. Uses installed Edge; no browser download/PrintDeps.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)('playwright');
const origin='http://127.0.0.1:4111';
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
let checks=0;
try{
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  await context.route('**/*',route=>new URL(route.request().url()).origin===origin?route.continue():route.abort());
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin+'/simple');
  await page.getByRole('heading',{name:'1. Connect your store'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Preview orders'}).isDisabled(),true);checks++;
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Verify and enable Test imports'}).click();
  await page.getByText('Connected for Test-account imports.').waitFor();checks++;
  await page.getByLabel('From (India time)').fill('2026-10-18');
  await page.getByLabel('Through (inclusive)').fill('2026-10-18');
  await page.getByRole('button',{name:'Preview orders'}).click();
  await page.getByRole('heading',{name:'3 orders found · 1 new'}).waitFor();
  assert.equal(await page.getByRole('cell').filter({hasText:'Reference matches an existing order'}).count(),1);
  assert.equal(await page.getByText('Conflict — not imported',{exact:true}).count(),1);checks+=2;
  await mkdir('outputs/shopify-unified',{recursive:true});
  await page.screenshot({path:'outputs/shopify-unified/setup-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Import 1 new orders'}).click();
  await page.getByText('Import finished. Open Orders to complete the draft.').waitFor();checks++;
  await page.getByRole('button',{name:'Preview orders'}).click();
  await page.getByRole('heading',{name:'3 orders found · 0 new'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Import 0 new orders'}).isDisabled(),true);checks++;
  await page.getByRole('button',{name:'Set up automatic sync'}).click();
  await page.getByText('Automatic sync is on for Phantom Threads Test.').waitFor();checks++;
  await page.getByRole('button',{name:'Turn off automatic sync'}).click();
  await page.getByText('Automatic sync is off.',{exact:true}).waitFor();checks++;
  await page.setViewportSize({width:375,height:812});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.screenshot({path:'outputs/shopify-unified/setup-mobile.png',fullPage:true});checks++;
  await page.goto(origin+'/manager');
  await page.getByRole('heading',{name:'Finish order setup'}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Complete setup'}).isDisabled(),true);
  await page.getByRole('button',{name:'Save draft'}).click();
  await page.getByText('Draft saved. No workflow has started.').waitFor();checks++;
  await page.getByLabel('Team setup note (optional)').fill('simulate network error');
  await page.getByRole('button',{name:'Save draft'}).click();
  await page.getByRole('alert').filter({hasText:'Could not confirm the result'}).waitFor();
  assert.equal(await page.getByLabel('Team setup note (optional)').inputValue(),'simulate network error');checks++;
  await page.getByLabel('Team setup note (optional)').fill('Fictional end-to-end check');
  await page.getByLabel('Delivery',{exact:true}).selectOption('store_pickup');
  await page.getByLabel('Garment type',{exact:true}).selectOption({label:'Pant'});
  await page.getByLabel('Workflow',{exact:true}).selectOption({label:'Pant default workflow'});
  assert.equal(await page.getByRole('button',{name:'Complete setup'}).isDisabled(),true);
  await page.getByRole('button',{name:'Save draft'}).click();
  await page.getByText('Draft saved. No workflow has started.').waitFor();
  await page.getByRole('button',{name:'Complete setup'}).waitFor();
  // Wait for the committed client action state, not only the repeated message.
  await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='Complete setup'&&!b.disabled));checks++;
  assert.equal(await page.getByLabel('Delivery',{exact:true}).inputValue(),'store_pickup');
  assert.equal(await page.getByLabel('Garment type',{exact:true}).inputValue(),'10000000-0000-4000-8000-000000000006');
  assert.equal(await page.getByLabel('Workflow',{exact:true}).inputValue(),'10000000-0000-4000-8000-000000000007');checks+=3;
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);checks++;
  await page.screenshot({path:'outputs/shopify-unified/manager-mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'outputs/shopify-unified/manager-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Complete setup'}).click();
  await page.getByText('Setup complete. Fictional Pant workflow started.').waitFor();
  assert.equal(await page.getByRole('button',{name:'Complete setup'}).isDisabled(),true);checks++;
  assert.deepEqual(errors,[]);checks++;
  console.log(`PASS ${checks} loopback browser assertions; fictional UI actions only.`);
}finally{await browser.close();}
