import { writeFile } from "node:fs/promises";

import dynamicIconImports from "lucide-react/dynamicIconImports.mjs";

const names = Object.keys(dynamicIconImports).sort((left, right) => left.localeCompare(right));
const source = `// Generated by scripts/generate-lucide-icon-catalog.mjs from the pinned lucide-react package.\nexport const lucideIconNames = ${JSON.stringify(names, null, 2)} as const;\n`;

await writeFile(new URL("../src/features/settings/lucide-icon-names.generated.ts", import.meta.url), source, "utf8");
console.log(`Generated ${names.length} Lucide icon names.`);
